(function (root, factory) {
  const api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  if (root) root.BootsplashCore = api;
})(typeof globalThis !== 'undefined' ? globalThis : this, function () {
  'use strict';

  const SAFE_SLUG = /^[a-z0-9][a-z0-9_-]{1,39}$/;
  const ALLOWED_ANIMATIONS = new Set(['spinner', 'pulse', 'none']);
  const ALLOWED_TYPES = new Set(['text', 'shape', 'logo', 'spinner', 'progress']);

  function slugify(value) {
    const slug = String(value || 'my-theme').normalize('NFKD')
      .replace(/[\u0300-\u036f]/g, '').toLowerCase()
      .replace(/[^a-z0-9_-]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 40);
    return SAFE_SLUG.test(slug) ? slug : 'my-theme';
  }

  function clamp(value, min, max) {
    const n = Number(value);
    return Number.isFinite(n) ? Math.max(min, Math.min(max, n)) : min;
  }

  function validateTheme(input) {
    if (!input || typeof input !== 'object' || Array.isArray(input)) throw new TypeError('Theme must be a JSON object.');
    const theme = structuredCloneSafe(input);
    theme.schemaVersion = 1;
    theme.name = String(theme.name || 'Untitled theme').trim().slice(0, 64) || 'Untitled theme';
    theme.slug = slugify(theme.slug || theme.name);
    theme.author = String(theme.author || '').trim().slice(0, 64);
    theme.description = String(theme.description || '').trim().slice(0, 180);
    theme.animation = ALLOWED_ANIMATIONS.has(theme.animation) ? theme.animation : 'spinner';
    theme.canvas = theme.canvas && typeof theme.canvas === 'object' ? theme.canvas : {};
    theme.canvas.width = 1920;
    theme.canvas.height = 1080;
    theme.canvas.background = /^#[0-9a-fA-F]{6}$/.test(theme.canvas.background || '') ? theme.canvas.background : '#080d18';
    if (!Array.isArray(theme.layers)) theme.layers = [];
    if (theme.layers.length > 80) throw new RangeError('A theme can contain at most 80 layers.');
    if (theme.layers.filter(layer => layer && layer.type === 'spinner').length > 1) throw new RangeError('A theme can contain only one animated spinner layer.');
    if (theme.layers.filter(layer => layer && layer.type === 'progress').length > 1) throw new RangeError('A theme can contain only one progress bar layer.');
    const ids = new Set();
    theme.layers = theme.layers.map((layer, index) => {
      if (!layer || typeof layer !== 'object' || !ALLOWED_TYPES.has(layer.type)) throw new TypeError(`Layer ${index + 1} has an unsupported type.`);
      const id = String(layer.id || `layer-${index + 1}`).replace(/[^a-zA-Z0-9_-]/g, '').slice(0, 48) || `layer-${index + 1}`;
      if (ids.has(id)) throw new TypeError(`Duplicate layer id: ${id}`);
      ids.add(id);
      const item = {
        id, type: layer.type,
        name: String(layer.name || `${layer.type} ${index + 1}`).slice(0, 64),
        visible: layer.visible !== false,
        locked: Boolean(layer.locked),
        x: clamp(layer.x, 0, 1920), y: clamp(layer.y, 0, 1080),
        width: clamp(layer.width, 1, 1920), height: clamp(layer.height, 1, 1080),
        color: /^#[0-9a-fA-F]{6}$/.test(layer.color || '') ? layer.color : '#eaf2ff',
        text: String(layer.text || '').slice(0, 180),
        fontSize: clamp(layer.fontSize || 56, 8, 240),
        fontFamily: ['Arial', 'Georgia', 'Verdana', 'monospace', 'sans-serif', 'serif'].includes(layer.fontFamily) ? layer.fontFamily : 'Arial',
        fontWeight: layer.fontWeight === '400' ? '400' : '700',
        radius: clamp(layer.radius || 24, 0, 400),
        opacity: clamp(layer.opacity === undefined ? 1 : layer.opacity, 0, 1),
        dataUrl: typeof layer.dataUrl === 'string' && /^data:image\/(?:png|jpeg|webp);base64,/i.test(layer.dataUrl) && layer.dataUrl.length < 4_300_000 ? layer.dataUrl : ''
      };
      if (item.type === 'text' && !item.text) item.text = 'Your brand';
      if (item.type === 'shape') item.shape = ['circle', 'pill', 'rect'].includes(layer.shape) ? layer.shape : 'rect';
      if (item.type === 'spinner') item.name = 'Loading indicator';
      if (item.type === 'progress') item.name = 'Progress bar';
      return item;
    });
    return theme;
  }

  function structuredCloneSafe(value) {
    return JSON.parse(JSON.stringify(value));
  }

  function plymouthQuote(value) {
    return '"' + String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/[\r\n]/g, ' ') + '"';
  }

  function generatePlymouthScript(theme) {
    const t = validateTheme(theme);
    const spinners = t.animation === 'spinner' ? t.layers.filter(l => l.type === 'spinner' && l.visible) : [];
    const progress = t.layers.find(l => l.type === 'progress' && l.visible);
    const pulseLogo = t.animation === 'pulse' ? t.layers.find(l => (l.type === 'logo' || l.type === 'text') && l.visible) : null;
    const scale = 'scale_factor';
    const lines = [
      '# Generated by Bootsplash Studio. Edit the source theme, not this file.',
      'screen_width = Window.GetWidth();',
      'screen_height = Window.GetHeight();',
      'scale_factor = screen_width / 1920;',
      'if (screen_height / 1080 < scale_factor) scale_factor = screen_height / 1080;',
      'offset_x = (screen_width - (1920 * scale_factor)) / 2;',
      'offset_y = (screen_height - (1080 * scale_factor)) / 2;',
      'background_image = Image("background.png");',
      'background_image = background_image.Scale(Math.Int(1920 * scale_factor), Math.Int(1080 * scale_factor));',
      'background_sprite = Sprite(background_image);',
      'background_sprite.SetPosition(offset_x, offset_y, -100);',
      'animation_tick = 0;',
    ];
    spinners.forEach((layer, index) => {
      lines.push(`spinner_${index}_sprite = Sprite(Image("spinner-00.png"));`);
      lines.push(`spinner_${index}_sprite.SetImage(Image("spinner-00.png").Scale(Math.Int(${Math.max(1, Math.round(layer.width))} * scale_factor), Math.Int(${Math.max(1, Math.round(layer.height))} * scale_factor)));`,
        `spinner_${index}_sprite.SetPosition(offset_x + (${layer.x} * scale_factor), offset_y + (${layer.y} * scale_factor), ${index + 20});`);
      lines.push(`spinner_${index}_images = NULL;`);
      for (let frame = 0; frame < 12; frame++) {
        lines.push(`spinner_${index}_images[${frame}] = Image("spinner-${String(frame).padStart(2, '0')}.png").Scale(Math.Int(${Math.max(1, Math.round(layer.width))} * scale_factor), Math.Int(${Math.max(1, Math.round(layer.height))} * scale_factor));`);
      }
    });
    if (progress) {
      lines.push('progress_background = Image("progress-bg.png");');
      lines.push('progress_fill_original = Image("progress-fill.png");');
      lines.push('progress_background = progress_background.Scale(Math.Int(' + Math.max(1, Math.round(progress.width)) + ' * scale_factor), Math.Int(' + Math.max(1, Math.round(progress.height)) + ' * scale_factor));');
      lines.push('progress_fill_original = progress_fill_original.Scale(Math.Int(' + Math.max(1, Math.round(progress.width)) + ' * scale_factor), Math.Int(' + Math.max(1, Math.round(progress.height)) + ' * scale_factor));');
      lines.push('progress_background_sprite = Sprite(progress_background);');
      lines.push(`progress_background_sprite.SetPosition(offset_x + (${progress.x} * scale_factor), offset_y + (${progress.y} * scale_factor), 40);`);
      lines.push('progress_fill_sprite = Sprite();');
      lines.push(`progress_fill_sprite.SetPosition(offset_x + (${progress.x} * scale_factor), offset_y + (${progress.y} * scale_factor), 41);`);
      lines.push('fun progress_callback (duration, progress) {');
      lines.push('  if (progress < 0) progress = 0; if (progress > 1) progress = 1;');
      lines.push('  fill_width = Math.Int(progress_fill_original.GetWidth() * progress); if (fill_width < 1) fill_width = 1;');
      lines.push('  progress_fill_sprite.SetImage(progress_fill_original.Scale(fill_width, progress_fill_original.GetHeight()));');
      lines.push('}');
      lines.push('Plymouth.SetBootProgressFunction(progress_callback);');
    }
    if (pulseLogo) {
      lines.push(`pulse_logo_image = Image("pulse-logo.png").Scale(Math.Int(${Math.max(1, Math.round(pulseLogo.width))} * scale_factor), Math.Int(${Math.max(1, Math.round(pulseLogo.height))} * scale_factor));`);
      lines.push(`pulse_sprite = Sprite(pulse_logo_image);`);
      lines.push(`pulse_sprite.SetPosition(offset_x + (${pulseLogo.x} * scale_factor), offset_y + (${pulseLogo.y} * scale_factor), 30);`);
      lines.push('pulse_phase = 0;');
    }
    if (spinners.length || pulseLogo) {
      lines.push('fun refresh_callback () {');
      lines.push('  animation_tick++;');
      spinners.forEach((_, index) => {
        lines.push(`  spinner_${index}_sprite.SetImage(spinner_${index}_images[Math.Int(animation_tick / 3) % 12]);`);
      });
      if (pulseLogo) lines.push('  pulse_phase += 0.07; pulse_sprite.SetOpacity(0.48 + (Math.Cos(pulse_phase) + 1) * 0.26);');
      lines.push('}');
      lines.push('Plymouth.SetRefreshFunction(refresh_callback);');
    }
    lines.push('');
    return lines.join('\n');
  }

  function generatePlymouthDescriptor(theme) {
    const t = validateTheme(theme);
    return [
      '[Plymouth Theme]',
      `Name=${t.name.replace(/[\r\n]/g, ' ')}`,
      `Description=${(t.description || 'Custom boot splash generated with Bootsplash Studio').replace(/[\r\n]/g, ' ')}`,
      'ModuleName=script',
      '',
      '[script]',
      `ImageDir=/usr/share/plymouth/themes/${t.slug}`,
      `ScriptFile=/usr/share/plymouth/themes/${t.slug}/${t.slug}.script`,
      ''
    ].join('\n');
  }


  function crc32(bytes) {
    let crc = -1;
    for (let i = 0; i < bytes.length; i++) {
      crc ^= bytes[i];
      for (let bit = 0; bit < 8; bit++) crc = (crc >>> 1) ^ (0xEDB88320 & -(crc & 1));
    }
    return (crc ^ -1) >>> 0;
  }

  function makeZip(entries) {
    if (!Array.isArray(entries) || entries.length > 65535) throw new TypeError('ZIP entries must be an array of at most 65535 items.');
    const encoder = new TextEncoder();
    const locals = [], centrals = [];
    let offset = 0;
    const now = new Date();
    const year = Math.max(1980, now.getFullYear());
    const date = ((year - 1980) << 9) | ((now.getMonth() + 1) << 5) | now.getDate();
    const time = (now.getHours() << 11) | (now.getMinutes() << 5) | Math.floor(now.getSeconds() / 2);
    const names = new Set();
    for (const entry of entries) {
      if (!entry || typeof entry.name !== 'string' || !entry.name.trim()) throw new TypeError('ZIP entries require a name.');
      const nameText = entry.name.replace(/^\/+/, '').replace(/\\/g, '/');
      if (nameText.split('/').some(part => part === '..' || part === '.')) throw new TypeError('ZIP entry path traversal is not allowed.');
      if (names.has(nameText)) throw new TypeError(`Duplicate ZIP entry: ${nameText}`);
      names.add(nameText);
      const name = encoder.encode(nameText);
      const data = entry.data instanceof Uint8Array ? entry.data : encoder.encode(String(entry.data ?? ''));
      const crc = crc32(data);
      const local = new Uint8Array(30 + name.length + data.length);
      const lv = new DataView(local.buffer);
      lv.setUint32(0, 0x04034b50, true); lv.setUint16(4, 20, true); lv.setUint16(6, 0x0800, true); lv.setUint16(8, 0, true);
      lv.setUint16(10, time, true); lv.setUint16(12, date, true); lv.setUint32(14, crc, true); lv.setUint32(18, data.length, true); lv.setUint32(22, data.length, true);
      lv.setUint16(26, name.length, true); lv.setUint16(28, 0, true); local.set(name, 30); local.set(data, 30 + name.length);
      locals.push(local);
      const central = new Uint8Array(46 + name.length);
      const cv = new DataView(central.buffer);
      cv.setUint32(0, 0x02014b50, true); cv.setUint16(4, 20, true); cv.setUint16(6, 20, true); cv.setUint16(8, 0x0800, true); cv.setUint16(10, 0, true);
      cv.setUint16(12, time, true); cv.setUint16(14, date, true); cv.setUint32(16, crc, true); cv.setUint32(20, data.length, true); cv.setUint32(24, data.length, true);
      cv.setUint16(28, name.length, true); cv.setUint16(30, 0, true); cv.setUint16(32, 0, true); cv.setUint16(34, 0, true); cv.setUint16(36, 0, true);
      const permissions = entry.name === 'install.sh' ? 0o100755 : 0o100644;
      cv.setUint32(38, permissions << 16, true); cv.setUint32(42, offset, true);
      central.set(name, 46); centrals.push(central);
      offset += local.length;
    }
    const centralSize = centrals.reduce((sum, part) => sum + part.length, 0);
    const end = new Uint8Array(22);
    const ev = new DataView(end.buffer);
    ev.setUint32(0, 0x06054b50, true); ev.setUint16(4, 0, true); ev.setUint16(6, 0, true); ev.setUint16(8, entries.length, true); ev.setUint16(10, entries.length, true);
    ev.setUint32(12, centralSize, true); ev.setUint32(16, offset, true); ev.setUint16(20, 0, true);
    return new Blob([...locals, ...centrals, end], { type: 'application/zip' });
  }

  function generateInstaller(theme) {
    const t = validateTheme(theme);
    const slug = t.slug;
    return `#!/usr/bin/env bash
# Bootsplash Studio generated installer. Requires a Linux system with Plymouth.
set -Eeuo pipefail

THEME='${slug}'
HERE="$(cd -- "$(dirname -- "\${BASH_SOURCE[0]}")" && pwd)"
PLYMOUTH_ROOT="/usr/share/plymouth/themes"
TARGET="$PLYMOUTH_ROOT/$THEME"
STATE_ROOT="/var/lib/bootsplash-studio"
BACKUP="$STATE_ROOT/$THEME"
GRUB_DEFAULT="/etc/default/grub"

info(){ printf '\\033[1;34m[info]\\033[0m %s\\n' "$*"; }
warn(){ printf '\\033[1;33m[warn]\\033[0m %s\\n' "$*" >&2; }
fail(){ printf '\\033[1;31m[error]\\033[0m %s\\n' "$*" >&2; exit 1; }
need_root(){ [[ "$(id -u)" -eq 0 ]] || fail "Run with sudo: sudo ./install.sh"; }

show_platform(){
  if [[ -r /etc/os-release ]]; then . /etc/os-release; info "Detected platform: \${PRETTY_NAME:-\${ID:-Linux}}"; else info "Detected platform: Linux (unknown distribution)"; fi
  if command -v update-initramfs >/dev/null 2>&1; then info "Initramfs tool: update-initramfs"
  elif command -v dracut >/dev/null 2>&1; then info "Initramfs tool: dracut"
  elif command -v mkinitcpio >/dev/null 2>&1; then info "Initramfs tool: mkinitcpio"
  else fail "No supported initramfs generator found."; fi
}

backup_once(){
  install -d -m 0700 "$BACKUP/files"
  if [[ ! -f "$BACKUP/installed" ]]; then
    [[ -f "$GRUB_DEFAULT" ]] && cp -a "$GRUB_DEFAULT" "$BACKUP/files/grub.default" || true
    [[ -f /etc/mkinitcpio.conf ]] && cp -a /etc/mkinitcpio.conf "$BACKUP/files/mkinitcpio.conf" || true
    if command -v plymouth-set-default-theme >/dev/null 2>&1; then
      plymouth-set-default-theme 2>/dev/null > "$BACKUP/previous-theme" || true
    elif [[ -L /etc/alternatives/default.plymouth ]]; then
      readlink -f /etc/alternatives/default.plymouth > "$BACKUP/previous-theme-path" || true
    fi
    touch "$BACKUP/installed"
  fi
}

configure_grub(){
  [[ -f "$GRUB_DEFAULT" ]] || { warn "No /etc/default/grub; leaving GRUB settings unchanged."; return 0; }
  python3 - "$GRUB_DEFAULT" <<'PY'
import pathlib, re, sys
p = pathlib.Path(sys.argv[1])
s = p.read_text()
key = 'GRUB_CMDLINE_LINUX_DEFAULT'
pat = re.compile(r'^(\\s*' + key + r'=)([\"\\'])(.*?)(\\2\\s*(?:#.*)?)$', re.M)
m = pat.search(s)
if m:
    args = m.group(3).split()
    for item in ('quiet', 'splash'):
        if item not in args: args.append(item)
    s = s[:m.start()] + m.group(1) + m.group(2) + ' '.join(args) + m.group(2) + m.group(4) + s[m.end():]
else:
    s += ('\\n' if s and not s.endswith('\\n') else '') + key + '=\\"quiet splash\\"\\n'
p.write_text(s)
PY
  if command -v update-grub >/dev/null 2>&1; then update-grub
  elif command -v grub-mkconfig >/dev/null 2>&1; then
    local out='/boot/grub/grub.cfg'
    [[ -d /boot/grub2 ]] && out='/boot/grub2/grub.cfg'
    grub-mkconfig -o "$out"
  else warn "GRUB generator not found; update GRUB manually if you use it."; fi
}

configure_plymouth(){
  install -d "$TARGET"
  cp -a "$HERE"/theme/. "$TARGET/" 2>/dev/null || true
  install -m 0644 "$HERE/$THEME.plymouth" "$TARGET/$THEME.plymouth"
  install -m 0644 "$HERE/$THEME.script" "$TARGET/$THEME.script"
  if command -v plymouth-set-default-theme >/dev/null 2>&1; then
    plymouth-set-default-theme "$THEME" -R
    INITRAMFS_REBUILT=1
  elif command -v update-alternatives >/dev/null 2>&1; then
    INITRAMFS_REBUILT=0
    update-alternatives --install /usr/share/plymouth/themes/default.plymouth default.plymouth "$TARGET/$THEME.plymouth" 100
    update-alternatives --set default.plymouth "$TARGET/$THEME.plymouth"
  else fail "No supported Plymouth theme selector found."; fi
}

configure_initramfs(){
  if command -v update-initramfs >/dev/null 2>&1; then
    update-initramfs -u -k all
  elif command -v dracut >/dev/null 2>&1; then
    install -d /etc/dracut.conf.d
    if [[ ! -f "$BACKUP/files/bootsplash-studio-dracut.conf" && -f /etc/dracut.conf.d/bootsplash-studio.conf ]]; then
      cp -a /etc/dracut.conf.d/bootsplash-studio.conf "$BACKUP/files/bootsplash-studio-dracut.conf"
    fi
    printf '%s\\n' 'add_dracutmodules+=" plymouth "' > /etc/dracut.conf.d/bootsplash-studio.conf
    dracut --regenerate-all --force
  elif command -v mkinitcpio >/dev/null 2>&1; then
    [[ -f /etc/mkinitcpio.conf ]] || fail "mkinitcpio found but /etc/mkinitcpio.conf is missing."
    python3 - /etc/mkinitcpio.conf <<'PY'
import pathlib, re, sys
p = pathlib.Path(sys.argv[1]); s = p.read_text()
m = re.search(r'(?m)^\\s*HOOKS=\\(([^)]*)\\)', s)
if not m: raise SystemExit('Cannot safely find HOOKS=(...) in mkinitcpio.conf')
hooks = m.group(1).split()
if 'plymouth' not in hooks:
    if 'systemd' in hooks: idx = hooks.index('systemd') + 1
    elif 'encrypt' in hooks: idx = hooks.index('encrypt')
    elif 'sd-encrypt' in hooks: idx = hooks.index('sd-encrypt')
    elif 'filesystems' in hooks: idx = hooks.index('filesystems')
    else: idx = len(hooks)
    hooks.insert(idx, 'plymouth')
    s = s[:m.start(1)] + ' '.join(hooks) + s[m.end(1):]
p.write_text(s)
PY
    mkinitcpio -P
  else
    fail "No supported initramfs generator found (update-initramfs, dracut, or mkinitcpio)."
  fi
}

install_theme(){
  need_root
  [[ -f "$HERE/$THEME.plymouth" && -f "$HERE/$THEME.script" && -f "$HERE/theme/background.png" ]] || fail "Theme package is incomplete. Extract the ZIP before running this script."
  command -v plymouth >/dev/null 2>&1 || fail "Plymouth is not installed. Install Plymouth and its script plugin first."
  show_platform
  backup_once
  info "Installing '$THEME' Plymouth theme..."
  INITRAMFS_REBUILT=0
  configure_plymouth
  configure_grub
  if [[ "$INITRAMFS_REBUILT" -eq 0 ]]; then configure_initramfs; fi
  info "Theme installed. Reboot to test it. Keep the recovery instructions in README-INSTALL.txt."
  warn "GRUB quiet mode hides most kernel messages; firmware, bootloader, driver, and display-manager output may still appear."
}

uninstall_theme(){
  need_root
  [[ -d "$BACKUP" ]] || fail "No Bootsplash Studio backup found for '$THEME'; refusing to guess previous settings."
  info "Restoring backed-up settings..."
  [[ -f "$BACKUP/files/grub.default" ]] && cp -a "$BACKUP/files/grub.default" "$GRUB_DEFAULT" || true
  [[ -f "$BACKUP/files/mkinitcpio.conf" ]] && cp -a "$BACKUP/files/mkinitcpio.conf" /etc/mkinitcpio.conf || true
  [[ -f "$BACKUP/files/bootsplash-studio-dracut.conf" ]] && cp -a "$BACKUP/files/bootsplash-studio-dracut.conf" /etc/dracut.conf.d/bootsplash-studio.conf || rm -f /etc/dracut.conf.d/bootsplash-studio.conf
  REBUILD_NEEDED=1
  if [[ -s "$BACKUP/previous-theme" ]] && command -v plymouth-set-default-theme >/dev/null 2>&1; then
    old="$(head -n 1 "$BACKUP/previous-theme" | tr -cd 'A-Za-z0-9_.-')"
    if [[ -n "$old" ]]; then plymouth-set-default-theme "$old" -R; REBUILD_NEEDED=0; else plymouth-set-default-theme --reset -R; REBUILD_NEEDED=0; fi
  elif [[ -s "$BACKUP/previous-theme-path" ]] && command -v update-alternatives >/dev/null 2>&1; then
    oldpath="$(cat "$BACKUP/previous-theme-path")"
    [[ -f "$oldpath" ]] && update-alternatives --set default.plymouth "$oldpath" || true
  fi
  rm -rf -- "$TARGET"
  if command -v update-grub >/dev/null 2>&1; then update-grub || true
  elif command -v grub-mkconfig >/dev/null 2>&1; then
    [[ -d /boot/grub2 ]] && grub-mkconfig -o /boot/grub2/grub.cfg || grub-mkconfig -o /boot/grub/grub.cfg || true
  fi
  if [[ "$REBUILD_NEEDED" -eq 1 ]]; then
    if command -v update-initramfs >/dev/null 2>&1; then update-initramfs -u -k all
    elif command -v dracut >/dev/null 2>&1; then dracut --regenerate-all --force
    elif command -v mkinitcpio >/dev/null 2>&1; then mkinitcpio -P; fi
  fi
  info "Theme files removed and backed-up settings restored."
  warn "Review your bootloader and Plymouth default manually before deleting the backup at $BACKUP."
}

case "\${1:-install}" in
  install) install_theme ;;
  --uninstall|uninstall) uninstall_theme ;;
  --help|-h) echo "Usage: sudo ./install.sh [install|--uninstall]" ;;
  *) fail "Unknown option: $1" ;;
esac
`;
  }

  return { slugify, validateTheme, generatePlymouthScript, generatePlymouthDescriptor, generateInstaller, makeZip, SAFE_SLUG };
});
